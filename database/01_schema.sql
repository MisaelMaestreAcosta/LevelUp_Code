-- =============================================================================
-- LEVELUP CODE - ESQUEMA RELACIONAL COMPLETO (18 TABLAS - ORACLE SQL)
-- Basado 100% en el Diccionario de Datos del documento de arquitectura.
-- Equivalencias Oracle aplicadas:
